const fs = require('fs');
const path = require('path');

const ROOT = process.cwd();
const SOURCE = path.join(ROOT, 'shared', 'contracts', 'dashboard.ts');
const TARGET = path.join(ROOT, 'backend', 'src', 'types', 'generated', 'dashboard.contract.ts');

function normalize(text) {
  return String(text || '').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n').trimEnd();
}

function main() {
  if (!fs.existsSync(SOURCE)) {
    throw new Error(`Dashboard shared contract source is missing: ${SOURCE}`);
  }

  const source = normalize(fs.readFileSync(SOURCE, 'utf8'));
  const output = [
    '/*',
    ' * Generated from shared/contracts/dashboard.ts.',
    ' * Run `npm run contracts:dashboard:backend` after changing the shared dashboard contract.',
    ' * Do not edit this file directly.',
    ' */',
    '',
    source,
    '',
  ].join('\n');

  fs.mkdirSync(path.dirname(TARGET), { recursive: true });
  fs.writeFileSync(TARGET, output, 'utf8');
  console.log(`Synced backend dashboard contract: ${path.relative(ROOT, TARGET).replace(/\\/g, '/')}`);
}

main();
