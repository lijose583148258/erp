const fs = require('fs');
const path = require('path');

const root = process.cwd();
const findings = [];
const read = (relativePath) => fs.readFileSync(path.join(root, relativePath), 'utf8');
const exists = (relativePath) => fs.existsSync(path.join(root, relativePath));
const add = (severity, file, message) => findings.push({ severity, file, message });

const apiRegistryPath = 'backend/src/routes/apiRegistry.ts';
const sdkPath = 'sdk/ailaoda-api-client.ts';
const sharedContractPath = 'shared/api-contract.ts';
const generatorPath = 'scripts/generate-api-sdk-v1.cjs';

if (!exists(generatorPath)) add('P1', generatorPath, 'API SDK generator is missing.');
if (!exists(sdkPath)) add('P1', sdkPath, 'Generated API SDK is missing.');
if (!exists(sharedContractPath)) add('P1', sharedContractPath, 'Generated shared API contract is missing.');

const registry = read(apiRegistryPath);
const sdk = exists(sdkPath) ? read(sdkPath) : '';
const sharedContract = exists(sharedContractPath) ? read(sharedContractPath) : '';
const modules = Array.from(registry.matchAll(/\{\s*path:\s*'([^']+)'\s*,\s*router:\s*\w+\s*,\s*tag:\s*'([^']+)'\s*,\s*summary:\s*'([^']+)'\s*,\s*requiresAuth:\s*(true|false)\s*\}/g))
  .map((match) => ({ path: match[1], tag: match[2], requiresAuth: match[4] === 'true' }));

if (modules.length === 0) add('P0', apiRegistryPath, 'No API route modules were found to generate SDK from.');

if (sdk) {
  for (const token of [
    'Generated by scripts/generate-api-sdk-v1.cjs',
    "from '../shared/api-contract'",
    'namespace || "/api/v1"',
    'headers.Authorization = `Bearer ${resolvedToken}`',
    'export class AilaoDaApiClient',
    'export class AilaoDaApiError',
    'AilaoDaApiResponse',
    'AilaoDaCustomerListQuery',
    'AilaoDaCustomerListResponse',
    'AilaoDaOrderListQuery',
    'AilaoDaOrderListResponse',
    'AilaoDaOrderImportRow',
    'AilaoDaOrderImportResponse',
    'AilaoDaCollectionOverdueListQuery',
    'AilaoDaCollectionOverdueListResponse',
    'listCustomers',
    'listOrders',
    'importOrders(orders: AilaoDaOrderImportRow[], idempotencyKey: string',
    '"Idempotency-Key": idempotencyKey',
    'listCollectionOverdueOrders',
  ]) {
    if (!sdk.includes(token)) add('P1', sdkPath, `Missing SDK contract token: ${token}`);
  }

  if (sdk.includes('export type AilaoDaApiResponse<T = unknown> =')) {
    add('P1', sdkPath, 'SDK should import AilaoDaApiResponse from shared/api-contract instead of redefining it.');
  }
}

if (sharedContract) {
  for (const token of [
    "export type AilaoDaApiNamespace = '/api' | '/api/v1'",
    'export type AilaoDaPaginationMeta',
    'export type AilaoDaApiResponse<T = unknown>',
    'export type AilaoDaCustomerListQuery',
    'export type AilaoDaCustomerListResponse',
    'export type AilaoDaOrderListQuery',
    'export type AilaoDaOrderListResponse',
    'export type AilaoDaOrderImportRow',
    'export type AilaoDaOrderImportResponse',
    'export type AilaoDaCollectionOverdueListQuery',
    'export type AilaoDaCollectionOverdueListResponse',
    'export const AILAO_DA_API_MODULES',
    'export type AilaoDaApiModulePath',
  ]) {
    if (!sharedContract.includes(token)) add('P1', sharedContractPath, `Missing shared API contract token: ${token}`);
  }

  const moduleEntries = Array.from(sharedContract.matchAll(/\{\s*path:\s*'([^']+)'\s*,\s*tag:\s*'([^']+)'/g)).map((match) => match[1]);
  if (moduleEntries.length !== modules.length) {
    add('P0', sharedContractPath, `Shared contract module count ${moduleEntries.length} does not match registry count ${modules.length}.`);
  }

  for (const routeModule of modules) {
    if (!sharedContract.includes(`path: '${routeModule.path}'`)) {
      add('P0', sharedContractPath, `Shared contract is missing module path ${routeModule.path}.`);
    }
  }
}

if (!exists('docs/adr/0008-generated-api-sdk-boundary.md')) {
  add('P1', 'docs/adr/0008-generated-api-sdk-boundary.md', 'Generated API SDK ADR is missing.');
}
if (!exists('scripts/api-sdk-runtime-audit-v1.ts')) {
  add('P1', 'scripts/api-sdk-runtime-audit-v1.ts', 'API SDK runtime contract audit is missing.');
}

if (findings.length) {
  console.error('API SDK Audit: FAIL');
  for (const finding of findings) {
    console.error(`[${finding.severity}] ${finding.file}: ${finding.message}`);
  }
  process.exit(1);
}

console.log('API SDK Audit: PASS');
console.log(`- Shared API contract covers ${modules.length} API route modules from apiRegistry.`);
console.log('- SDK defaults to /api/v1 and supports Bearer auth injection.');
console.log('- Endpoint-specific list helpers cover high-frequency customer, order, and collection overdue reads.');
console.log('- Bulk order import has a typed, idempotency-key-required SDK helper and runtime contract audit.');
console.log('- Generated shared contract, SDK boundary, and ADR are present.');
